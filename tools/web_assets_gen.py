#!/usr/bin/env python3
"""Gzip the portal in web/ into src/web/web_assets.h.

The panel serves the portal out of loop(), so the picture stands still while a
browser is pulling it. The page, its style and its script are 144 KB of flash
sent as plain text; gzipped they are under 33 KB, and the browser unpacks them
for free.

The sources are the plain files in web/. The header is generated and not
committed: the build runs this before every compile (tools/web_assets_build.py),
and it can be run by hand:

  python3 tools/web_assets_gen.py

The header is only rewritten when its content changes, so a build with no
portal edits does not recompile web.cpp. Each rewrite prints the sizes.

portal.css is written readable and minified here: comments go, and so does the
whitespace around { } ; - none of which CSS needs. Keep a ; or a brace inside a
string or url() free of surrounding spaces, or they would go as well.

The page is static: what used to be a %TOKEN% resolved while the page streamed
is fetched from /api/portal instead. One thing is still resolved here, at build
time and never on the panel:

  ?v=%ASSETVER%   after /portal.css and /portal.js: that file's own content
                  hash, so a browser keeps its copy for exactly as long as the
                  bytes stay the same

and two things are refused, because either would ship a page that cannot work:

  * any %TOKEN% left in the page - nothing resolves them any more;
  * a named control in the settings form that handlePortalValues() does not
    fill - it would show its HTML default, and Save would write that back.
"""

import gzip, hashlib, io, os, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "web"
OUT = ROOT / "src/web/web_assets.h"

# (file in web/, name in the generated header, what it is served as)
ASSETS = [
    ("portal.css", "PORTAL_CSS_GZ", "/portal.css"),
    ("portal.js", "PORTAL_JS_GZ", "/portal.js"),
    ("favicon.svg", "FAVICON_SVG_GZ", "/favicon.svg"),
    ("index.html", "PAGE_HTML_GZ", "/"),
]

# Controls in the settings form that are not settings, with why.
NOT_SETTINGS = {
    "resetSpriteColors": "resets the sprite colors on this one save; unchecked on every load",
    "resetScope": "restores the oscilloscope defaults on this one save; unchecked on every load",
}


def check_page(page, web_cpp):
    """Refuse a page the firmware can no longer fill."""
    left = sorted(set(re.findall(r"%[A-Z0-9_]{2,}%", page)))
    if left:
        raise SystemExit("web_assets_gen: nothing resolves these any more: " + ", ".join(left))
    filled = set(re.findall(r'form\["([A-Za-z0-9_]+)"\]', web_cpp))
    named = set()
    for tag in re.findall(r"<(?:input|select|textarea)\b[^>]*>", page):
        name = re.search(r'name="([^"]+)"', tag)
        if not name or 'type="submit"' in tag:
            continue
        named.add(name[1])
    missing = sorted(n for n in named - filled if n not in NOT_SETTINGS)
    if missing:
        raise SystemExit("web_assets_gen: handlePortalValues() does not fill " + ", ".join(missing) +
                         " - the page would show its HTML default, and Save would write that back.")


def source_text(name):
    path = SRC / name
    if not path.exists():
        raise SystemExit(f"web_assets_gen: missing web/{name}")
    # Same text whatever line endings the checkout gave the file.
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def minify_css(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    return re.sub(r"\s*([{};])\s*", r"\1", css).strip().replace(";}", "}")


def deflate(data):
    buf = io.BytesIO()
    # mtime 0 and no file name: the same bytes on every build.
    with gzip.GzipFile(fileobj=buf, mode="wb", compresslevel=9, mtime=0) as gz:
        gz.write(data)
    return buf.getvalue()


def c_array(name, blob):
    lines = [f"static const uint8_t {name}[] PROGMEM = {{"]
    for i in range(0, len(blob), 16):
        row = ", ".join("0x%02x" % b for b in blob[i:i + 16])
        lines.append(f"  {row},")
    lines.append("};")
    return "\n".join(lines)


def build():
    web_cpp = (ROOT / "src/web/web.cpp").read_text(encoding="utf-8")
    sources = {name: source_text(name) for name, _, _ in ASSETS}
    sources["portal.css"] = minify_css(sources["portal.css"])
    # ?v= carries each file's own hash, so one changing does not expire the other.
    for name in ("portal.css", "portal.js"):
        digest = hashlib.sha256(sources[name].encode("utf-8")).hexdigest()[:12]
        sources["index.html"] = sources["index.html"].replace(f"/{name}?v=%ASSETVER%", f"/{name}?v={digest}")
    check_page(sources["index.html"], web_cpp)
    parts = [
        "// Generated by tools/web_assets_gen.py from web/ - do not edit, not committed.",
        "",
        "#ifndef WEB_ASSETS_H",
        "#define WEB_ASSETS_H",
        "",
        "#include <Arduino.h>",
        "",
    ]
    report = []
    for name, cname, url in ASSETS:
        raw = sources[name].encode("utf-8")
        blob = deflate(raw)
        parts.append(f"// {url}: {len(raw):,} B source -> {len(blob):,} B gzip")
        parts.append(c_array(cname, blob))
        parts.append("")
        report.append((url, len(raw), len(blob)))
        if name == "index.html":
            parts.append('#define WEB_INDEX_ETAG "\\"%s\\""' % hashlib.sha256(blob).hexdigest()[:12])
            parts.append("")
    parts.append("#endif // WEB_ASSETS_H")
    return "\n".join(parts) + "\n", report


def main():
    text, report = build()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
    if current == text:
        return 0
    # Via a temporary file, so a build of another env never sees half a header.
    tmp = OUT.with_name(f"{OUT.name}.{os.getpid()}.tmp")
    with tmp.open("w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.replace(tmp, OUT)
    print(f"web_assets_gen: wrote {OUT.relative_to(ROOT).as_posix()}")
    for url, raw, blob in report:
        print(f"  {url:<14} {raw:>8,} B -> {blob:>7,} B ({blob * 100 // raw}%)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
